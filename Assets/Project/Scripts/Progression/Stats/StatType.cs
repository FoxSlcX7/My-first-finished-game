public enum StatType
{
    // Базовые статы игрока
    Damage,           // Множитель урона (1.0 = 100%)
    MoveSpeed,        // Множитель скорости (1.0 = 100%)
    Cooldown,         // Множитель кулдаунов (1.0 = 100%, меньше = быстрее)
    BonusProjectiles, // Дополнительные снаряды (+1, +2 и т.д.)

    //Legendary механики
    RicochetBounces,  // Количество рикошетов
    LifeSteal,        // Вампиризм (0.15 = 15% урона возвращается как HP)
    ChainTargets,     // Цели цепной молнии
    ChainDamage,      // Множитель урона цепи (0.5 = 50%)

    // Будущие статы (Неделя 12+)
    CritChance,       // Шанс крита (0.25 = 25%)
    CritDamage,       // Множитель урона крита (2.0 = 200%)
    Armor,            // Снижение урона (0.2 = 20%)
    PickupRadius,     // Радиус подбора орбов
    XPBoost           // Множитель опыта (1.2 = +20%)
}